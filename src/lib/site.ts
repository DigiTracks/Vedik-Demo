/** Absolute URL for a route path, always with a trailing slash to match `trailingSlash: true`. */
export function siteUrl(path = "/"): string {
  const clean = path === "/" ? "" : path.replace(/\/+$/, "");
  return `${SITE_URL}${clean}/`;
}

