export type RouteKey = keyof typeof ROUTES;

export const ROUTE_KEYS = Object.keys(ROUTES) as RouteKey[];

export function routeMeta(key: RouteKey): RouteMeta {
  return ROUTES[key];
}

/** Breadcrumb trail from the landing page down to `key`, inclusive. */
export function breadcrumbsFor(key: RouteKey): RouteMeta[] {
  const meta = ROUTES[key];
  const trail: RouteMeta[] = [];
  let cursor: RouteMeta | undefined = meta;
  while (cursor) {
    trail.unshift(cursor);
    cursor = cursor.parent ? ROUTES[cursor.parent as RouteKey] : undefined;
  }
  return trail;
}

