/**
 * Build a per-page `Metadata` object from the route registry.
 *
 * Titles intentionally omit the brand suffix here: the root layout supplies a
 * `title.template` so each page renders as "Page Title | VEDIK School ERP".
 * Pages that are already branded (landing, pricing) set `absolute`.
 */
export function buildMetadata(
  key: RouteKey,
  overrides?: Partial<Pick<Metadata, "title" | "description" | "keywords">>,
): Metadata {
  const meta = ROUTES[key];
  const description = meta.description;
  const title =
    typeof overrides?.title === "string"
      ? overrides.title
      : (overrides?.title as { absolute?: string } | undefined)?.absolute ??
        meta.title;

  return {
    title,
    description,
    keywords: overrides?.keywords ?? [...SITE_KEYWORDS],
    alternates: { canonical: siteUrl(meta.path) },
    openGraph: {
      type: "website",
      siteName: SITE.name,
      locale: SITE.locale,
      url: siteUrl(meta.path),
      title,
      description,
      images: [
        {
          url: OG_IMAGE.url,
          width: OG_IMAGE.width,
          height: OG_IMAGE.height,
          alt: OG_IMAGE.alt,
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [
        {
          url: OG_IMAGE.twitterUrl,
          width: OG_IMAGE.width,
          height: OG_IMAGE.height,
          alt: OG_IMAGE.alt,
        },
      ],
    },
  };
}

