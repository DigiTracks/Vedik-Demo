/**
 * Serialise a schema.org graph into a safe inline JSON-LD script body.
 *
 * `<` is escaped to prevent an attacker-controlled string from closing the
 * script tag, per the Next.js JSON-LD guide.
 */
export function jsonLdPayload(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

